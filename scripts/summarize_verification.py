#!/usr/bin/env python3
"""Print the result tables of a verification run as markdown, straight from its JSON.

Usage:
    python scripts/summarize_verification.py docs/results/verify_dev_frozen.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ARMS = {
    "B0": "B0 judge only", "B3": "B3 + citation rules", "N": "N + NEI recheck only", "B1p": "B1p + LLM polarity",
    "B2p": "B2p + NLI polarity", "B1": "B1 LLM polarity + NEI recheck", "B2": "B2 NLI polarity + NEI recheck",
    "oracle": "Oracle (gold abstracts, no critic)",
}


def fmt(x, digits=3):
    return "n/a" if x is None else f"{x:.{digits}f}"


def pr(summary: dict, label: str) -> str:
    """Precision / recall of one class as a table cell."""
    cls = summary["per_class"][label]
    return f"{cls['precision']:.2f} / {cls['recall']:.2f}"


def faith_cell(f: dict) -> str:
    return "n/a (no checker)" if f["rate"] is None else f"{f['rate']:.3f} ({f['faithful']}/{f['judged']})"


def exploratory_error_anatomy(res: dict) -> None:
    """EXPLORATORY (not declared in advance): where the no-critic baseline's errors come from."""
    from agentrag.bench.registry import CACHE
    from agentrag.verify import data as sf_data

    gold = {c.id: c for c in sf_data.load(CACHE).dev}
    b0 = res["arms"]["B0"]
    print("\n### Exploratory: anatomy of the baseline's (B0) errors\n")
    print("| Gold \\ predicted | SUPPORT | CONTRADICT | NOT_ENOUGH_INFO |")
    print("| --- | --- | --- | --- |")
    for label, row in b0["metrics"]["initial"]["confusion"].items():
        print(f"| {label} | {row['SUPPORT']} | {row['CONTRADICT']} | {row['NOT_ENOUGH_INFO']} |")
    claims = b0["claims"]
    false_nei = [c for c in claims if c["initial"] == "NOT_ENOUGH_INFO" and c["gold"] != "NOT_ENOUGH_INFO"]
    retrieved = sum(bool(gold[c["id"]].evidence_docs & set(c["retrieved"])) for c in false_nei)
    swapped = [c for c in claims if {c["initial"], c["gold"]} == {"SUPPORT", "CONTRADICT"}]
    false_decisive = [c for c in claims if c["gold"] == "NOT_ENOUGH_INFO" and c["initial"] != "NOT_ENOUGH_INFO"]
    print(f"\n{len(false_nei)} of the {sum(c['gold'] != 'NOT_ENOUGH_INFO' for c in claims)} claims that have evidence "
          f"were answered NOT_ENOUGH_INFO; for {retrieved} of them a gold evidence document was in the "
          f"retrieved top 5. "
          f"{len(swapped)} claims had SUPPORT and CONTRADICT swapped (the error a polarity check targets); "
          f"{len(false_decisive)} NOT_ENOUGH_INFO claims got a decisive verdict.")


def main(path: str) -> None:
    res = json.loads(Path(path).read_text(encoding="utf-8"))
    arms, cfg = res["arms"], res["config"]
    n = len(res["claims"])
    print(f"<!-- generated by scripts/summarize_verification.py from {Path(path).name}; {n} claims, "
          f"fingerprint {cfg['fingerprint']} -->\n")

    print("### Verdicts versus the human labels\n")
    print("| Arm | Macro-F1 | Îº | Accuracy | SUPPORT P / R | CONTRADICT P / R | NEI P / R | Macro-F1 (abstain) |")
    print("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for key, label in ARMS.items():
        if key not in arms:
            continue
        m = arms[key]["metrics"]
        k = m["final_keep"]
        print(f"| {label} | {k['macro_f1']:.3f} | {k['kappa']:.3f} | {k['accuracy']:.3f} | {pr(k, 'SUPPORT')} | "
              f"{pr(k, 'CONTRADICT')} | {pr(k, 'NOT_ENOUGH_INFO')} | {m['final_abstain']['macro_f1']:.3f} |")
    if "A" in arms:
        a = arms["A"]["metrics"]["final_keep"]
        pc = a["per_class"]
        print(f"| A: NLI model alone, no LLM (Ï„={arms['A']['tau']}) | {a['macro_f1']:.3f} | {a['kappa']:.3f} | "
              f"{a['accuracy']:.3f} | {pc['SUPPORT']['precision']:.2f} / {pc['SUPPORT']['recall']:.2f} | "
              f"{pc['CONTRADICT']['precision']:.2f} / {pc['CONTRADICT']['recall']:.2f} | "
              f"{pc['NOT_ENOUGH_INFO']['precision']:.2f} / {pc['NOT_ENOUGH_INFO']['recall']:.2f} | n/a |")

    gold_counts = arms["B0"]["metrics"]["initial"]["per_class"]
    print(f"\nClass counts: SUPPORT {gold_counts['SUPPORT']['support']}, CONTRADICT "
          f"{gold_counts['CONTRADICT']['support']}, NOT_ENOUGH_INFO {gold_counts['NOT_ENOUGH_INFO']['support']}.\n")

    print("### The critic and the retry loop\n")
    print("| Arm | Flagged | Fixed | Harmed | Fix rate | Harm rate | Critic precision | Critic recall | "
          "On NEI verdicts: flagged / fixed / harmed |")
    print("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for key in ("B3", "N", "B1p", "B2p", "B1", "B2"):
        if key not in arms:
            continue
        m = arms[key]["metrics"]
        r, s = m["retry_keep"], m["retry_nei_subset"] or {}
        print(f"| {ARMS[key]} | {r['flagged']} | {r['fixed']} | {r['harmed']} | {fmt(r['fix_rate'], 2)} | "
              f"{fmt(r['harm_rate'], 2)} | {fmt(r['critic_precision'], 2)} | {fmt(r['critic_recall'], 2)} | "
              f"{s.get('flagged', 0)} / {s.get('fixed', 0)} / {s.get('harmed', 0)} |")
    print("\nFix rate = fixed Ã· (initially wrong and flagged); harm rate = harmed Ã· (initially right and flagged); "
          "critic precision = flagged claims that were wrong; critic recall = wrong claims that were flagged.\n")

    print("### Faithfulness and cited evidence\n")
    print("| Arm | Faithfulness, first answer | Faithfulness, final answer | Cited-sentence P / R / F1 |")
    print("| --- | --- | --- | --- |")
    for key in ("B0", "B1p", "B2p", "B1", "B2", "oracle"):
        if key not in arms:
            continue
        m = arms[key]["metrics"]
        fi, ff, ev = m["faithfulness_initial"], m["faithfulness_final"], m["evidence"]
        print(f"| {ARMS[key]} | {faith_cell(fi)} | {faith_cell(ff)} | "
              f"{ev['precision']:.2f} / {ev['recall']:.2f} / {ev['f1']:.2f} |")

    cv = res.get("checker_validation", {})
    if cv:
        print("\n**Polarity checkers against human-marked evidence** (items built from gold rationale sentences):\n")
        print("| Checker | Items | Contradictions recovered | Entailments recovered | "
              "Mismatched controls called neutral |")
        print("| --- | --- | --- | --- | --- |")
        for name, v in cv.items():
            g, s = v["gold"], v["shuffled"]
            print(f"| {name.upper()} | {v['items']['gold']} gold + {v['items']['shuffled']} controls | "
                  f"{g['per_class']['contradicts']['recall']:.3f} (n={g['per_class']['contradicts']['n']}) | "
                  f"{g['per_class']['entails']['recall']:.3f} (n={g['per_class']['entails']['n']}) | "
                  f"{s['per_class']['neutral']['recall']:.3f} (n={s['n']}) |")

    print("\n### Retrieval ceiling versus the oracle arm\n")
    r = res["retrieval"]
    print(f"On the claims with evidence, the retriever puts a gold evidence document in the top 1 for "
          f"{r['evidence_doc_hit@1']:.1%} and in the top 5 for {r['evidence_doc_hit@5']:.1%}.\n")
    if "oracle" in arms:
        b0, o = arms["B0"]["metrics"]["final_keep"], arms["oracle"]["metrics"]["final_keep"]
        print("| | Macro-F1 | Îº | SUPPORT R | CONTRADICT R | NEI R |")
        print("| --- | --- | --- | --- | --- | --- |")
        for label, m in (("B0 (retrieved top 5)", b0), ("Oracle (gold abstracts)", o)):
            pc = m["per_class"]
            print(f"| {label} | {m['macro_f1']:.3f} | {m['kappa']:.3f} | {pc['SUPPORT']['recall']:.2f} | "
                  f"{pc['CONTRADICT']['recall']:.2f} | {pc['NOT_ENOUGH_INFO']['recall']:.2f} |")

    print("\n### Declared comparisons (95% paired-bootstrap CI, Holm across all 16 tests)\n")
    print("| Tier | Comparison (A âˆ’ B) | Metric | Difference | 95% CI | p | Holm p |")
    print("| --- | --- | --- | --- | --- | --- | --- |")
    for row in res["declared_comparisons"]:
        print(f"| {row['tier']} | {row['comparison']} | {row['metric'].replace('_', ' ')} | {row['mean_diff']:+.3f} | "
              f"[{row['ci_low']:+.3f}, {row['ci_high']:+.3f}] | {row['p_value']:.4f} | {row['p_holm']:.4f} |")

    print("\n### Exploratory comparisons (not declared in advance; no correction)\n")
    print("| Policy | Comparison (A âˆ’ B) | Metric | Difference | 95% CI |")
    print("| --- | --- | --- | --- | --- |")
    declared = {(r["comparison"], r["metric"]) for r in res["declared_comparisons"]}
    for key, t in res["comparisons"].items():
        pair, policy, metric = (part.strip() for part in key.split("|"))
        if policy == "keep" and (pair, metric) in declared:
            continue
        print(f"| {policy} | {pair} | {metric.replace('_', ' ')} | {t['mean_diff']:+.3f} | "
              f"[{t['ci_low']:+.3f}, {t['ci_high']:+.3f}] |")

    print("\n### Cost, latency and thinking per arm\n")
    print("| Arm | LLM calls | Cost per claim | Cost per call, max / mean | Thinking tokens, max / mean per call | "
          "API latency per claim, mean / p95 |")
    print("| --- | --- | --- | --- | --- | --- |")
    for key, label in ARMS.items():
        if key not in arms:
            continue
        u = arms[key]["metrics"]["usage"]
        print(f"| {label} | {u['llm_calls_total']} | ${u['paid_equivalent_usd_per_claim']:.4f} | "
              f"${u['max_call_usd']:.4f} / ${u['mean_call_usd']:.4f} | {u['max_thought_tokens']} / "
              f"{u['mean_thought_tokens_per_call']:.1f} | {u['api_latency_ms_per_claim_mean'] / 1000:.1f} s / "
              f"{u['api_latency_ms_per_claim_p95'] / 1000:.1f} s |")

    exploratory_error_anatomy(res)

    s = res["spend"]
    print(f"\nSpend: this run sent {s['api_requests_this_run']} requests; lifetime on this key "
          f"{s['lifetime_calls']} requests, ${s['lifetime_usd']:.4f} = Rs {s['lifetime_inr']:.2f}; "
          f"{s['wall_seconds'] / 60:.0f} minutes of wall time with {s['workers']} workers.")


if __name__ == "__main__":
    main(sys.argv[1])
