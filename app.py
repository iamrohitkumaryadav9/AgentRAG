"""AgentRAG demo: upload documents (or use the samples), ask questions, see how the agents reached the answer.

Run locally with ``streamlit run app.py``. Deploys to Streamlit Community Cloud as-is (see README, "Live demo").

All logic lives in ``agentrag.app_support`` (tested without Streamlit); this file is layout and session state.
A visitor's Gemini key lives only in ``st.session_state`` and is handed straight to the Gemini client: it is never
put in the environment, logged, cached or written to disk, and the app writes no files at runtime.
"""
from __future__ import annotations

from pathlib import Path

import streamlit as st

from agentrag import app_support as core

REPO_URL = "https://github.com/iamrohitkumaryadav9/AgentRAG"
SAMPLE_DIR = Path(__file__).parent / "data" / "sample_docs"
PATH_LABELS = {
    "answer": "answer (retrieve, then synthesise, then check)",
    "refuse": "refuse (retrieval did not cover the question)",
    "direct": "direct (small talk, no retrieval)",
}

st.set_page_config(page_title="AgentRAG demo", page_icon="🔎", layout="wide")


@st.cache_resource(show_spinner="Loading the bge-small embedding model (first use only)…")
def load_dense_model():
    """One embedding model shared by every session (a Cloud app has ~1 GB of RAM). Holds no user data or keys."""
    from sentence_transformers import SentenceTransformer

    return SentenceTransformer(core.HYBRID_DENSE_MODEL)


def md_table(rows: list[dict]) -> None:
    """A markdown table; avoids st.table/st.dataframe, which pull in pyarrow, for what are tiny tables."""
    if not rows:
        return
    headers = list(dict.fromkeys(key for row in rows for key in row))  # union: rows may differ in keys
    cell = lambda v: str(v).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(r.get(h, "")) for h in headers) + " |" for r in rows]
    st.markdown("\n".join(lines))


def sample_files() -> list[tuple[str, bytes]]:
    return [(p.name, p.read_bytes()) for p in sorted(SAMPLE_DIR.glob("*.md"))]


def sidebar() -> tuple[str, str | None]:
    """Draws the sidebar; returns (retrieval backend, API key or None)."""
    with st.sidebar:
        st.header("Settings")
        key = st.text_input(
            "Gemini API key (optional)",
            type="password",
            key="gemini_api_key",
            placeholder="Paste a key to use Gemini",
            help="Without a key the app answers with an offline extractive generator that needs no API.",
        ).strip()
        st.caption(
            "Your key is used only for this browser session and is never stored: not in a file, a log, a cache or "
            "an environment variable. Closing the tab discards it."
        )
        if key:
            st.success("Gemini mode: answers are generated by Gemini using your key.")
        else:
            st.info("Offline mode: answers are stitched together from the retrieved text, with no API calls.")

        st.divider()
        if core.dense_available():
            hybrid = st.toggle(
                "Hybrid (BM25 + bge-small)",
                key="use_hybrid",
                help="Fuses keyword and semantic search. Slower to index and capped at "
                f"{core.chunk_cap('hybrid'):,} chunks (BM25: {core.chunk_cap('bm25'):,}).",
            )
        else:
            hybrid = False
            st.toggle(
                "Hybrid (BM25 + bge-small)",
                value=False,
                disabled=True,
                help="Needs the optional dense extra: pip install 'agentrag[dense]'. This deployment uses BM25.",
            )
        backend = "hybrid" if hybrid else "bm25"
        st.caption(f"Retrieval: **{backend}** · index cap: {core.chunk_cap(backend):,} chunks")
    return backend, key or None


def choose_documents() -> list[tuple[str, bytes]]:
    st.subheader("1 · Documents")
    left, right = st.columns([3, 1])
    with left:
        uploads = st.file_uploader(
            "Upload PDF, Markdown or text files",
            type=["pdf", "md", "txt"],
            accept_multiple_files=True,
            help="Up to 50 MB per file. The index is limited by total chunks rather than number of files.",
        )
    with right:
        st.write("")
        st.write("")
        if st.button("Use sample docs", use_container_width=True):
            st.session_state["use_samples"] = True
    if uploads:
        st.session_state["use_samples"] = False  # uploads take over from the samples
        return [(f.name, f.getvalue()) for f in uploads]
    if st.session_state.get("use_samples"):
        return sample_files()
    return []


def ensure_index(files: list[tuple[str, bytes]], backend: str) -> core.IndexBundle | None:
    """Rebuild the index only when the documents or the retrieval backend changed since the last build."""
    if not files:
        st.session_state.pop("bundle", None)
        st.session_state.pop("report", None)
        return None
    signature = core.documents_signature(files, backend)
    bundle = st.session_state.get("bundle")
    if bundle is not None and bundle.signature == signature:
        return bundle

    st.session_state.pop("report", None)
    bar = st.progress(0.0, text="Starting…")
    try:
        bundle = core.build_index(
            files,
            backend,
            progress=lambda fraction, message: bar.progress(min(1.0, fraction), text=message),
            dense_model=load_dense_model() if backend == "hybrid" else None,
        )
    except core.NoIndexableText as err:
        st.session_state.pop("bundle", None)
        bar.empty()
        st.error(f"Nothing could be indexed. {err}")
        return None
    except Exception as err:  # noqa: BLE001 - never leave the visitor with a blank page
        st.session_state.pop("bundle", None)
        bar.empty()
        st.error(f"Indexing failed ({type(err).__name__}). Try fewer or smaller files, or BM25 retrieval.")
        return None
    bar.empty()
    st.session_state["bundle"] = bundle
    return bundle


def show_ingest(bundle: core.IndexBundle) -> None:
    ingest = bundle.ingest
    message = f"{ingest.summary()} Built the {bundle.backend} index in {bundle.seconds:.1f}s."
    if ingest.truncated:
        st.warning(message)
    elif any(f.status == "unreadable" for f in ingest.files):
        st.warning(message)
    else:
        st.success(message)
    with st.expander("Files"):
        md_table(
            [
                {
                    "file": f.name,
                    "status": f.status,
                    "chunks indexed": f.chunks_indexed,
                    "chunks in file": "—" if f.chunks_available is None else f.chunks_available,
                    "note": f.detail,
                }
                for f in ingest.files
            ]
        )


def ask(bundle: core.IndexBundle, api_key: str | None) -> None:
    st.subheader("2 · Ask a question")
    with st.form("ask_form", clear_on_submit=False):
        question = st.text_area(
            "Question",
            max_chars=core.MAX_QUESTION_CHARS,
            height=90,
            placeholder="e.g. What does the critic agent check?",
        )
        submitted = st.form_submit_button("Ask", type="primary")
    if not submitted:
        return
    try:
        cleaned = core.validate_question(question)
    except core.QuestionError as err:
        st.warning(str(err))
        return
    try:
        with st.spinner("Routing, retrieving, answering and checking…"):
            llm = core.make_llm(api_key)  # built per question, never stored
            st.session_state["report"] = core.answer_question(bundle, cleaned, llm)
    except Exception as err:  # noqa: BLE001
        st.session_state.pop("report", None)
        problem = core.friendly_error(err, secret=api_key)
        st.error(problem.message)
        with st.expander("Technical detail"):
            st.code(problem.detail)


def show_report(report: core.QueryReport) -> None:
    st.subheader("3 · Result")
    st.markdown(f"**Q:** {report.question}")
    st.markdown(report.answer)

    a, b, c, d = st.columns(4)
    a.metric("Router path", report.path)
    b.metric("Attempts", report.attempts)
    if report.critic_passed is None:
        c.metric("Critic", "not run")
        d.metric("Grounding score", "—")
    else:
        c.metric("Critic verdict", "passed" if report.critic_passed else "rejected")
        d.metric("Grounding score", f"{report.grounding_score:.2f}")
    st.caption(
        f"{PATH_LABELS[report.path]} · retrieval: {report.retrieval} · generator: {report.generation} · "
        f"{report.total_ms:,.0f} ms total · ~{report.est_tokens:,} tokens"
    )
    if report.critic_passed is False:
        st.warning(f"The critic did not accept this answer after {report.attempts} attempt(s): {report.critic_reason}")
    for flag in report.pii_flags:
        st.warning(f"Possible personal data in the answer: {flag}")

    st.markdown("**Citations**")
    if not report.citations:
        st.caption("None: nothing was cited for this response.")
    for cite in report.citations:
        label = f"{cite.source} · chunk {cite.position}"
        with st.expander(label if cite.found else f"{label} (not in the retrieved context)"):
            st.write(cite.snippet or "The cited chunk was not among the retrieved passages.")

    with st.expander("Agent trace and latency"):
        md_table(
            [
                {"agent": s.agent, "latency (ms)": round(s.ms, 2), **{k: str(v) for k, v in s.details.items()}}
                for s in report.spans
            ]
        )
        st.code("\n".join(report.trace), language="text")
    if report.sources:
        with st.expander("Retrieved passages"):
            md_table([{"source": src, "score": round(score, 4)} for src, score in report.sources])


def about() -> None:
    st.divider()
    with st.expander("About"):
        st.markdown(
            "AgentRAG is a small multi-agent RAG system: a **router** decides whether to retrieve, a **retriever** "
            "finds passages, a **synthesizer** drafts a cited answer, and a **critic** checks the answer against the "
            "retrieved text and can send it back for another attempt. If retrieval does not cover the question, the "
            "system refuses rather than guessing.\n\n"
            f"* [Source code on GitHub]({REPO_URL})\n"
            f"* [Key results (retrieval ablation and claim-verification study)]({REPO_URL}#key-results)\n\n"
            "Uploaded documents are held in memory for your session only; nothing is written to disk."
        )


def main() -> None:
    st.title("AgentRAG demo")
    st.caption(
        "Ask questions over your own documents. Every answer shows its citations, the critic's verdict and the trace."
    )
    backend, api_key = sidebar()
    files = choose_documents()
    bundle = ensure_index(files, backend)
    if bundle is None:
        st.info("Upload one or more documents, or press **Use sample docs**, to get started.")
    else:
        show_ingest(bundle)
        ask(bundle, api_key)
        report = st.session_state.get("report")
        if report is not None:
            show_report(report)
    about()


main()
